/** Правила аудита по типу воронки — чтобы AI не путал микро-цель этапа с финальной продажей. */

const WEBINAR_RULES = `
### ВЕБИНАРНАЯ ВОРОНКА (typeId: webinar)

Это МНОГОШАГОВАЯ воронка. «Цель воронки» в данных — финальный результат (продажа курса/продукта).
Страница регистрации НЕ обязана продавать основной продукт, НЕ обязана показывать его цену и НЕ обязана содержать «мост» к платному продукту.
Главная и достаточная цель reg page = регистрация на вебинар (выбор слота / отправка формы).

Микро-цели по этапам:
— reg_page / registration: регистрация на вебинар (бесплатно ИЛИ платный триал/депозит — нормально, если это явная точка входа)
— attendance / retention: доходимость и удержание на эфире
— selling_block / webinar_lead: заявка или покупка с вебинара
— followup / sale: дожим и оплата

НОРМАЛЬНО и НЕ является проблемой на reg page:
— Два (или больше) времени/слота вебинара в один день: «11:00 и 19:00», «утро / вечер», выбор «Иду сегодня в …» — это стандартная практика для охвата аудитории и роста регистраций
— Нет упоминания основного платного курса/чека на посадочной — продажа идёт на эфире и в дожиме, не на reg page
— CTA только про регистрацию на вебинар, без upsell основного продукта

ЗАПРЕЩЕНО фиксировать как critical/important problem и ЗАПРЕЩЕНО рекомендовать в quickWins / hypotheses:
— «Оффер на посадочной не соответствует цели продать курс за X ₽»
— «На лендинге нет цены основного продукта / не продаётся курс за 209 000»
— «CTA должен вести на покупку основного продукта» (на reg page CTA = регистрация на вебинар)
— «Убрать формулировки с временем / убрать выбор 11:00 и 19:00 / оставить один слот» — несколько слотов = норма
— «Добавить мост к платному продукту на reg page» / «нет связи с основным продуктом на лендинге» — мост не обязателен на reg page
— Любая гипотеза, где success = «снижение оттока регистрация→доходимость» через УДАЛЕНИЕ слотов времени

ЧТО проверять на reg_page и в blocks[] (как страницу регистрации, НЕ как продающий лендинг курса):
— Реклама обещает вебинар → на странице есть тема, дата/формат, результат вебинара, CTA «Зарегистрироваться»
— Понятен ли выбор времени (если слотов несколько) — UX, не «убрать слоты»
— Нет ли разрыва: в рекламе «вебинар», на странице другой продукт без объяснения связи
— Техника формы, скорость, мобильная версия, ясность «что будет на вебинаре»

Продажу основного чека оценивай ТОЛЬКО на этапах selling_block, webinar_lead, followup, sale — сценарий эфира, продающий блок, письма дожима.
metricName в hypotheses для reg page: «Конверсия страницы в регистрацию», «Стоимость регистрации», «CTR на регистрацию», «Доля выбора слота» — не «CR в покупку курса».
`.trim();

const CONSULTATION_RULES = `
### КОНСУЛЬТАЦИОННАЯ / LEAD (typeId: consultation, service_lead)

Посадочная продаёт не продукт, а следующий шаг: заявка / запись на консультацию / звонок.
Не требуй полного прайса и оплаты на первом экране, если цель — лид.
`.trim();

const ONLINE_COURSE_RULES = `
### ОНЛАЙН-КУРС (typeId: online_course)

Различай: бесплатный/дешёвый лид-магнит → прогрев → продажа курса. Точка входа может не содержать цену основного курса.
`.trim();

const CONTENT_MARKETING_RULES = `
### КОНТЕНТ-МАРКЕТИНГ (typeId: content_marketing)

Inbound-воронка на органическом трафике: SEO, соцсети, блог, YouTube, рассылка. Платная реклама НЕ обязательна — не требуй «рекламный бюджет», CPC, ROAS как базовые метрики, если пользователь явно не ведёт платный трафик.

Микро-цели по этапам:
— traffic (органический охват): переходы из поиска, ленты, рекомендаций
— content_entry / content_engagement: просмотр и вовлечение (дочитывание, досмотр, время)
— lead_magnet: подписка / скачивание лид-магнита
— nurture: прогревающая серия (email, мессенджер)
— lead / consultation / sale: заявка, созвон, оплата

НЕ считай проблемой:
— Отсутствие рекламных креативов и медиабюджета
— Отсутствие цены основного продукта в статье или видео
— Мягкий CTA «скачать гайд» вместо «купить сейчас»
— Длинный прогрев перед заявкой

Оценивай продажу на этапах lead, consultation, sale — страница услуги, скрипт, оффер после прогрева.
`.trim();

const GENERAL = `
### ОБЩЕЕ ПРАВИЛО МНОГОШАГОВЫХ ВОРОНОК

funnelGoal = финальная цель всей цепочки. На каждом этапе своя микро-цель (следующий шаг).
Не сравнивай оффер точки входа с финальной продажей — это методологическая ошибка аудита.
crossMaterialMismatches: только реальные противоречия между каналами (реклама vs reg page vs скрипт), не «нет цены основного продукта на reg page».
`.trim();

export function funnelTypeAuditRules(typeId: string): string {
  const id = String(typeId || "").toLowerCase();
  const parts = [GENERAL];
  if (id === "webinar") parts.push(WEBINAR_RULES);
  if (id === "consultation" || id === "service_lead") parts.push(CONSULTATION_RULES);
  if (id === "online_course") parts.push(ONLINE_COURSE_RULES);
  if (id === "content_marketing") parts.push(CONTENT_MARKETING_RULES);
  return parts.join("\n\n");
}
